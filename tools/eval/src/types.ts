export interface SamplingProfile {
  temperature: number;
  topP: number;
  presencePenalty?: number;
  frequencyPenalty?: number;
}

export interface TestCaseRun {
  caseId: CaseId;
  variant?: string;
  subtest?: string;
  systemPrompt: string;
  userPrompt: string;
  sampling: SamplingProfile;
  maxTokens: number;
  rerun?: number;
}

export interface AutoScore {
  score: number | null;
  explanation: string;
  evidence?: string[];
}

export interface CaseResult {
  caseId: CaseId;
  variant?: string;
  subtest?: string;
  runIndex?: number;
  systemPrompt: string;
  userPrompt: string;
  sampling: SamplingProfile;
  maxTokens: number;
  output: string;
  usage: { inputTokens: number; outputTokens: number };
  durationMs: number;
  finishReason: string;
  scores: Record<string, AutoScore>;
  redFlags: string[];
  /** Sub-results for rerun cases (TC-05). Each entry has its own output + scores. */
  runs?: CaseResult[];
}

export interface RuntimeMeta {
  name: string;
  endpoint: string;
  modelInfo?: string;
}

export interface ArchitectureObservations {
  memoryDecay?: string;
  promptFormat?: string;
  samplingNotes?: string;
}

/**
 * A concrete, actionable suggestion derived from observed failures.
 * Goal: future runs of this eval (or downstream `packages/llm-adapter` /
 * `packages/prompt-library` work) get a punch-list of things to try.
 */
export interface Suggestion {
  /** Stable id so the same observation across runs can be diffed. */
  code: string;
  /** Short, imperative; rendered as a heading. */
  title: string;
  /** "global" applies to whole eval; case-id strings scope to one TC. */
  scope: "global" | string;
  /** Detailed body (markdown allowed). Should explain WHAT was observed and WHAT to try. */
  body: string;
  /** Where the user would change something (eval CLI / prompt / runtime / sampling). */
  area: "endpoint" | "prompt" | "sampling" | "runtime" | "post-processing" | "other";
}

export interface EvaluationReport {
  startedAt: string;
  completedAt: string;
  runtime: RuntimeMeta;
  cases: CaseResult[];
  architectureObs: ArchitectureObservations;
  /** Generated by `scoring/suggestions.ts` — empty for early/failure runs. */
  suggestions: Suggestion[];
}
